def extract_helpers(corrupt: str) -> dict:
    """Извлечь хелперы Выполнить* из повреждённого хвоста."""
    helpers = {}
    pat = re.compile(
        r'&НаКлиенте\s*\n\s*Процедура\s+(Выполнить\w+)\(([^)]*)\)\s*\n([\s\S]*?)\n\s*КонецПроцедуры',
        re.MULTILINE,
    )
    for m in pat.finditer(corrupt):
        name, params, body = m.group(1), m.group(2), m.group(3)
        if len(body.strip()) < 3 or body.strip().endswith('Устано'):
            continue
        if name not in helpers or len(body) > len(helpers[name][1]):
            helpers[name] = (params, body)
    return helpers


def format_helper(name, params, body):
    return f'&НаКлиенте\nПроцедура {name}({params})\n{body}\n\nКонецПроцедуры\n\n'


def repair_file(path, patches: dict, extra_helpers: dict):
    with open(path, encoding='utf-8-sig') as f:
        text = f.read()
    text = text.replace('\r\n', '\n')
    marker = '#Область СтатистикаРаботыВнутреннихМеханизмов'
    idx = text.find(marker)
    if idx < 0:
        print('NO MARKER', path)
        return
    head = text[:idx]
    corrupt = text[idx:]
    helpers = extract_helpers(corrupt)
    helpers.update(extra_helpers)
    for name, (params, body) in patches.items():
        helpers[name] = (params, body)
    # порядок: как в вызовах команд (алфавит по имени)
    block = marker + '\n\n'
    for name in sorted(helpers.keys()):
        params, body = helpers[name]
        block += format_helper(name, params, body)
    block += STATS_TEMPLATE_TAIL
    out = head + block
    if '\r\n' in text:
        out = out.replace('\n', '\r\n')
    with open(path, 'w', encoding='utf-8-sig', newline='') as f:
        f.write(out)
    print('OK', path, len(helpers), 'helpers')


